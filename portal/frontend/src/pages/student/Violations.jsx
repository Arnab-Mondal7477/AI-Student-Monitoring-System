import React, { useState, useEffect } from 'react';
import axios from 'axios';
import { useAuth } from '../../context/AuthContext';
import { AlertTriangle, Clock, Info, CheckCircle } from 'lucide-react';

const StudentViolations = () => {
  const [violations, setViolations] = useState([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    fetchViolations();
  }, []);

  const fetchViolations = async () => {
    try {
      const token = localStorage.getItem('token');
      const response = await axios.get('http://localhost:5000/api/student/violations', {
        headers: { Authorization: `Bearer ${token}` }
      });
      setViolations(response.data);
    } catch (error) {
      console.error('Error fetching violations:', error);
    } finally {
      setLoading(false);
    }
  };

  const handleAppeal = async (id) => {
    const confirmAppeal = window.confirm("Are you sure you want to appeal this violation? This will notify your department head.");
    if (!confirmAppeal) return;

    try {
      const token = localStorage.getItem('token');
      await axios.post(`http://localhost:5000/api/student/violations/${id}/appeal`, 
        {}, 
        { headers: { Authorization: `Bearer ${token}` } }
      );
      alert('Appeal submitted successfully.');
      fetchViolations();
    } catch (error) {
      console.error('Error appealing violation:', error);
      alert('Failed to submit appeal');
    }
  };

  if (loading) return <div className="loader-container"><div className="loader"></div></div>;

  return (
    <div>
      <div className="header">
        <div>
          <h1>My Disciplinary Records</h1>
          <p>AI Monitoring History</p>
        </div>
      </div>
      
      {violations.length === 0 ? (
        <div className="glass-panel" style={{ padding: '4rem', textAlign: 'center', display: 'flex', flexDirection: 'column', alignItems: 'center' }}>
          <CheckCircle size={64} style={{ color: 'var(--success)', marginBottom: '1rem' }} />
          <h2 style={{ fontSize: '1.25rem' }}>Perfect Record!</h2>
          <p style={{ color: 'var(--text-muted)' }}>You have no monitoring violations on record.</p>
        </div>
      ) : (
        <div style={{ display: 'grid', gap: '1.5rem' }}>
          <div style={{ background: 'rgba(59, 130, 246, 0.1)', borderLeft: '4px solid #3b82f6', padding: '1rem', borderRadius: '0.5rem', display: 'flex', gap: '1rem' }}>
            <Info color="#3b82f6" size={24} />
            <p style={{ fontSize: '0.9rem', color: '#1e3a8a' }}>
              These records are automatically generated by the AI Monitoring System. If you believe a record is incorrect, you may submit an appeal to your teacher.
            </p>
          </div>

          {violations.map(v => (
            <div key={v.id} className="glass-panel" style={{ padding: '1.5rem', display: 'flex', gap: '2rem' }}>
              <div style={{ flex: 1 }}>
                <div style={{ display: 'flex', alignItems: 'center', gap: '0.75rem', marginBottom: '1rem' }}>
                  <AlertTriangle color={v.status === 'PENDING' ? 'var(--danger)' : 'var(--warning)'} size={24} />
                  <h3 style={{ fontSize: '1.25rem', textTransform: 'capitalize' }}>{v.detection_type ? v.detection_type.replace('_', ' ') : 'Unknown Violation'}</h3>
                  <span className={`badge ${
                    v.status === 'PENDING' ? 'badge-danger' : 
                    v.status === 'APPEALED' ? 'badge-primary' : 'badge-success'
                  }`}>
                    {v.status}
                  </span>
                </div>
                
                <p style={{ color: 'var(--text-muted)', fontSize: '0.9rem', display: 'flex', alignItems: 'center', gap: '0.25rem', marginBottom: '1rem' }}>
                  <Clock size={16} /> Recorded on {new Date(v.timestamp).toLocaleString()}
                </p>

                {(v.status === 'PENDING' || v.status === 'ACKNOWLEDGED') && (
                  <button 
                    onClick={() => handleAppeal(v.id)}
                    style={{ background: 'none', border: 'none', color: 'var(--primary)', fontWeight: 600, cursor: 'pointer', textDecoration: 'underline' }}
                  >
                    Submit Appeal
                  </button>
                )}
              </div>
              
              {v.evidence_path && (
                <div style={{ width: '280px', height: '180px', background: '#e2e8f0', borderRadius: '0.5rem', overflow: 'hidden' }}>
                  <a href={`http://localhost:5000/evidence/${v.evidence_path}`} target="_blank" rel="noreferrer">
                    <img 
                      src={`http://localhost:5000/evidence/${v.evidence_path}`} 
                      alt="Evidence" 
                      style={{ width: '100%', height: '100%', objectFit: 'cover' }}
                      onError={(e) => {
                        e.target.onerror = null;
                        e.target.src = 'https://via.placeholder.com/280x180/e2e8f0/475569?text=Evidence+Not+Found';
                      }}
                    />
                  </a>
                </div>
              )}
            </div>
          ))}
        </div>
      )}
    </div>
  );
};

export default StudentViolations;
